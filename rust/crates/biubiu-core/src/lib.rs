//! BiuBiu 的平台无关业务核心（spec `001-biubiu-core-crux`）。
//!
//! # 边界
//!
//! 这个 crate 里的一切都在**决定**，没有一样在**执行**。一个业务域收到
//! [`Event`]，更新它的 `Model`，返回 `Command` —— 要么重新渲染，要么向宿主声明
//! 一个 `Operation`（「请扫描这条链上这个地址的授权」「请在 6 秒后叫我」）。
//! 宿主执行，把 `ShellResult` 送回来。
//!
//! 这里没有网络、没有存储、没有时钟、没有随机数、没有 FFI —— 这正是业务规则
//! 能在不起浏览器、不联网、不等真实时间的条件下被证明的原因（宪法原则 I、V）。
//!
//! # 为什么规则要住在这里
//!
//! 迁移前，同一类正确性问题在每个 Svelte store 里被各自重新解决，语义互不相同：
//! revoke 用私有的 `scanGen` 单调计数器丢弃陈旧扫描，updown 用另一套协调机制，
//! 多数 store 什么都没有。「切链后旧结果不得落到新链」这条规则，过去只能靠
//! 起浏览器、造竞态来验证，因此实际上从未被验证过。
//!
//! 放进核心后它有名字、有测试，而且只有一处实现（宪法原则 III）。
//!
//! # 布局
//!
//! - [`app`] —— 每个业务域一个模块，各自拥有 Event / Model / ViewModel /
//!   Operation / ShellResult 与自己的业务单测。
//!
//! 全部内容只在 `--features crux` 下编译；默认构建不含。

#[cfg(feature = "crux")]
